/** 组装某城市的锦囊卡片（内置库优先，通用模板兜底） */
export function buildHandbook(city: string): BuiltinCard[] {
  const hit = matchHandbookCity(city);
  if (hit) return CITY_HANDBOOKS[hit].map(c => ({ ...c }));
  const base = genericCards(city);
  // 若目的地疑似出境但没有语言卡，附一张通用外语应急卡
  if (isOutbound(city)) {
    base.push(phrase('🗣️', '应急外语卡', '记住这几句，通关、问路、点餐都不慌。', [
      ['Excuse me', '不好意思/劳驾'],
      ['How much is it?', '多少钱？'],
      ['Where is the toilet?', '洗手间在哪？'],
      ['The bill, please', '请结账'],
      ['Thank you!', '谢谢！'],
    ]));
  }
  return base;
}

/* ================= AI 生成（可选增强） ================= */

const HANDBOOK_SYSTEM = `你是旅行锦囊编辑。根据目的地生成旅行锦囊卡片，输出 JSON：
{"cards":[{"category":"food|tip|phrase|photo","icon":"一个 emoji","title":"卡片标题","summary":"一句话简介","items":[{"label":"条目短标签，可空","text":"条目内容"}]}]}
要求：4-6 张卡；food 为当地必吃与觅食技巧；tip 为交通/门票预约/注意；phrase 仅出境目的地提供（含发音标注）；photo 为拍摄建议；每张卡 4-6 条目，内容具体可执行、不要空话；只输出 JSON。`;

/** AI 生成锦囊，失败返回 null（调用方回退内置） */
export async function aiHandbook(city: string, days: number, interests: string[]): Promise<BuiltinCard[] | null> {
  if (!aiConfigured()) return null;
  const prompt = `目的地：${city}\n行程：${days} 天\n偏好：${interests.join('、') || '不限'}\n请生成锦囊卡片 JSON。`;
  const out = await chat(HANDBOOK_SYSTEM, prompt, 45000);
  if (!out) return null;
  try {
    const m = out.match(/```(?:json)?\s*([\s\S]*?)```/);
    const raw = m ? m[1] : out;
    const start = raw.search(/[[{]/);
    if (start < 0) return null;
    const json = JSON.parse(raw.slice(start));
    const cards = (json.cards || json || []) as any[];
    if (!Array.isArray(cards) || !cards.length) return null;
    const validCat: GuideCategory[] = ['food', 'tip', 'phrase', 'photo'];
    const result: BuiltinCard[] = [];
    for (const c of cards.slice(0, 8)) {
      const category = validCat.includes(c.category) ? c.category : 'tip';
      const items = (Array.isArray(c.items) ? c.items : [])
        .map((it: any) => typeof it === 'string' ? { text: it } : { label: it.label ? String(it.label).slice(0, 40) : undefined, text: String(it.text || '').slice(0, 200) })
        .filter((it: GuideItem) => it.text)
        .slice(0, 8);
      if (!items.length) continue;
      result.push({
        category,
        icon: String(c.icon || '📌').slice(0, 4),
        title: String(c.title || '').slice(0, 30) || '锦囊',
        summary: String(c.summary || '').slice(0, 120),
        items,
      });
    }
    return result.length ? result : null;
  } catch {
    return null;
  }
}

