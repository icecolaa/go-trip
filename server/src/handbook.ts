/* ============================================================
 * 旅行锦囊内置内容库
 * 参考 personalized-travel-guide 手册模块：美食 / 贴士 / 语言 / 拍摄
 * 未配置 AI 或 AI 失败时，按目的地匹配内置卡片，保证任何城市都有产出
 * ============================================================ */

interface BuiltinCard {
  category: GuideCategory;
  icon: string;
  title: string;
  summary: string;
  items: GuideItem[];
}

function food(icon: string, title: string, summary: string, items: (string | [string, string])[]): BuiltinCard {
  return { category: 'food', icon, title, summary, items: items.map(toItem) };
}
function tip(icon: string, title: string, summary: string, items: (string | [string, string])[]): BuiltinCard {
  return { category: 'tip', icon, title, summary, items: items.map(toItem) };
}
function phrase(icon: string, title: string, summary: string, items: (string | [string, string])[]): BuiltinCard {
  return { category: 'phrase', icon, title, summary, items: items.map(toItem) };
}
function photo(icon: string, title: string, summary: string, items: (string | [string, string])[]): BuiltinCard {
  return { category: 'photo', icon, title, summary, items: items.map(toItem) };
}
function toItem(v: string | [string, string]): GuideItem {
  return Array.isArray(v) ? { label: v[0], text: v[1] } : { text: v };
}

