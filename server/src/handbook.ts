/* 目的地别名归一：substring 命中即认为匹配 */
export function matchHandbookCity(destination: string): string | null {
  const d = (destination || '').trim();
  if (!d) return null;
  for (const key of Object.keys(CITY_HANDBOOKS)) {
    if (d.includes(key)) return key;
  }
  return null;
}

